    /// <summary>Returns the 8 row bytes of a character; unknown characters render as a space.</summary>
    public static System.ReadOnlySpan<byte> Glyph(char c)
    {
        int index = c - FirstChar;
        if (index < 0 || index >= CharCount)
            index = 0;
        return new System.ReadOnlySpan<byte>(Data, index * GlyphHeight, GlyphHeight);
    }

    /// <summary>True when pixel (x, y) of the glyph is set.</summary>
    public static bool IsSet(char c, int x, int y)
    {
        if ((uint)x >= GlyphWidth || (uint)y >= GlyphHeight)
            return false;
        return (Glyph(c)[y] & (1 << (GlyphWidth - 1 - x))) != 0;
    }
